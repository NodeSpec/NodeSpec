// D2 (docs/WORK_LOOP_PLAN.md): `.nodespec/BOARD.md` — the git projection of
// the work board. ONE checkbox line per criterion and per task, grouped by
// requirement, with the derived status line and the node/test columns. ZERO
// prose: every line matches the grammar below (the no-prose test enforces
// it); rationale lives in the per-node task docs, never here.
//
// THE FILE IS A PROJECTION, NEVER A SECOND TRUTH. It is regenerated on every
// push from the same inputs the canvas board reads (deriveWorkStatus — the
// literal same function, cross-runtime). Ticks made IN the file ingest
// through the SAME delta lanes task docs use: parseBoardMd feeds
// computeCriterionDeltas and computeTaskDeltas unchanged, the deltas ride
// the change card next to the task-doc deltas, and apply happens through the
// existing apply lanes (tick-only, approval-gated). Any line this parser
// cannot attribute is FLAGGED, never guessed.
//
// LAYOUT (owner refinement 2026-08-21 — "a table in git, quick triage"):
// a GFM SUMMARY TABLE heads the file — one row per requirement with status
// emoji + aligned criteria/tasks/tests counts, each row anchor-linked to its
// detail section — because pulled or viewed on GitHub, the file must READ as
// a board. GFM renders checkboxes only as list items (never in table cells),
// so ticking stays in the sections below, and the sections align the three
// evidence lanes per requirement: Criteria (tickable) · Tasks (tickable) ·
// Tests (read-only status glyphs + the plan file's path — tests flip via
// report_test_results, never a checkbox).
//
// Grammar (every non-blank line is one of):
//   # Work Board <!-- nodespec-board v1 -->
//   <!-- ... -->                                  (instruction comment)
//   | ... |                                       (summary table rows)
//   ## <REQ-id> — <name> <!-- r:<REQ-id> -->
//   status: <derived> · criteria n/m · tasks n/m · tests p/f/s of t
//   ### Criteria
//   ### Tasks — <node label> <!-- n:<node uuid> -->
//   ### Tests — <plan path>   (path present when the plan artifact exists)
//   - [ ] / - [x] checkbox lines (criterion text, or task with <!-- t:key -->)
//     ↳ tasks: …/tests: … read-only LATERAL annotation under a criterion
//   - ✅/❌/▫️ <test id> — <name> read-only test lines ( (stale) suffixed)

